#!/usr/bin/env python3
"""サブモジュールのコードを src/ に生成する(生成物は手で編集しない)

    python tools/vendor.py            下の SOURCES のとおり third_party/ から src/ へ写す
    python tools/vendor.py --check    src/ の生成物が最新か確認(lint から呼ばれる)
    python tools/vendor.py --dirty    サブモジュールの未コミット変更も取り込む(試行錯誤用)

改変はそれぞれのリポジトリのブランチにコミットとして積み、出典を追跡できるようにする。
生成ファイルの先頭には出典のリポジトリとコミットを書く。古くなった生成物の削除は、
同じリポジトリから生成されたファイル(先頭の Source 行で判定)だけを対象にする。
ROMFS に入れるため生成先は src/ の下。src の直下(または直下のパッケージ)にすると、
dev.py run/test で src をマウントしたときも ROMFS でも、読み込みパスの追加なしで import できる。
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARK = "# GENERATED by tools/vendor.py"


class Source:
    def __init__(self, sub: str, url: str, branch: str, src_dir: str, pattern: str, dest: str):
        self.sub = ROOT / "third_party" / sub  # サブモジュール
        self.sub_name = sub
        self.url = url
        self.branch = branch
        self.src_dir = src_dir  # サブモジュール内のディレクトリ("" = 直下)
        self.pattern = pattern  # 写すファイル(glob)
        self.dest = ROOT / dest  # 生成先ディレクトリ
        self.dest_name = dest


SOURCES = [
    # micro-aprs(GPL-3.0、本家 stephanelsmith/micro-aprs のフォーク)の pico2 向けサブセット
    Source("micro-aprs", "https://github.com/klaNath/micro-aprs", "pico2-subset",
           "src/pico2", "*.py", "src/tnc"),
    # u-blox MAX-M10 ドライバ(MIT)
    Source("micropython-maxm10", "https://github.com/klaNath/micropython-maxm10", "pico2-aprs",
           "maxm10", "*.py", "src/maxm10"),
    # NMEA パーサ(MIT、inmcm/micropyGPS -> ekspla -> klaNath)
    Source("micropyGPS", "https://github.com/klaNath/micropyGPS", "pico2-aprs",
           "", "micropyGPS.py", "src"),
]


def git(src: Source, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(src.sub), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def render(src: Source, dirty: bool) -> dict[str, str]:
    d = src.sub / src.src_dir if src.src_dir else src.sub
    if not d.is_dir():
        sys.exit(f"[vendor] {d} がありません(git submodule update --init を確認)")
    rel = src.src_dir or "."
    status = git(src, "status", "--porcelain", "--", rel)
    if status and not dirty:
        sys.exit(
            f"[vendor] {src.sub_name}/{rel} に未コミットの変更があります。"
            "サブモジュール側でコミットするか --dirty を付けてください\n" + status
        )
    sha = git(src, "rev-parse", "HEAD")
    rev = sha[:7] + ("+dirty" if status else "")
    out = {}
    for f in sorted(d.glob(src.pattern)):
        path = f"{src.src_dir}/{f.name}" if src.src_dir else f.name
        head = (
            f"{MARK} - DO NOT EDIT.\n"
            f"# Edit third_party/{src.sub_name}/{path} (branch {src.branch}) and re-run it.\n"
            f"# Source: {src.url}/blob/{sha}/{path}  # noqa: E501\n"
            f"# Revision: {rev}\n"
        )
        out[f.name] = head + f.read_text(encoding="utf-8")
    return out


def existing(src: Source) -> dict[str, Path]:
    """生成先にある、このリポジトリから生成されたファイル"""
    if not src.dest.is_dir():
        return {}
    return {p.name: p for p in src.dest.glob("*.py") if _source_url(p) == src.url}


def main() -> int:
    for s in (sys.stdout, sys.stderr):  # 直接実行したときも UTF-8 で出す(Windows の既定は cp932)
        s.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dirty", action="store_true")
    a = ap.parse_args()

    rc = 0
    for src in SOURCES:
        want = render(src, a.dirty or a.check)
        have = existing(src)
        if a.check:
            bad = []
            for name, text in want.items():
                p = src.dest / name
                # 出典行(コミット)以外が一致すれば OK(サブモジュールでコミットしただけでは古くならない)
                if not p.exists() or _body(p.read_text(encoding="utf-8")) != _body(text):
                    bad.append(name)
            bad += [n for n in have if n not in want]
            if bad:
                print(f"[vendor] {src.dest_name}/ が古い: {bad} → python tools/vendor.py を実行してください")
                rc = 1
            continue
        src.dest.mkdir(parents=True, exist_ok=True)
        for name, text in want.items():
            p = src.dest / name
            if p.exists() and not _generated(p):
                sys.exit(f"[vendor] {src.dest_name}/{name} は手書きのファイルなので上書きしません")
            p.write_text(text, encoding="utf-8", newline="\n")
        for name, p in have.items():
            if name not in want:
                p.unlink()
                print(f"[vendor] 削除: {src.dest_name}/{name}")
        print(f"[vendor] {src.sub_name}: {len(want)} ファイルを {src.dest_name}/ に生成しました")
    return rc


def _generated(p: Path) -> bool:
    return p.read_text(encoding="utf-8").startswith(MARK)


def _source_url(p: Path) -> str | None:
    """生成物の Source 行からリポジトリの URL を取り出す(生成物でなければ None)"""
    with p.open(encoding="utf-8") as f:
        head = [f.readline() for _ in range(4)]
    if not head[0].startswith(MARK):
        return None
    for line in head:
        if line.startswith("# Source: "):
            return line[len("# Source: "):].split("/blob/")[0]
    return None


def _body(text: str) -> str:
    return "\n".join(
        line for line in text.splitlines() if not line.startswith(("# Source: ", "# Revision: "))
    )


if __name__ == "__main__":
    sys.exit(main())
