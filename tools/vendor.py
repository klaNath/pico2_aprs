#!/usr/bin/env python3
"""micro-aprs 由来のコードを src/tnc/ に生成する(src/tnc/ は手で編集しない)

    python tools/vendor.py            third_party/micro-aprs/src/pico2/*.py → src/tnc/
    python tools/vendor.py --check    src/tnc/ が生成結果と一致するか確認(lint から呼ばれる)
    python tools/vendor.py --dirty    サブモジュールの未コミット変更も取り込む(試行錯誤用)

改変はすべてフォーク(klaNath/micro-aprs)の pico2-subset ブランチにコミットとして積み、
本家との差分を追跡できるようにする。生成ファイルの先頭には出典のコミットを書く。
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUB = ROOT / "third_party" / "micro-aprs"
SRC_DIR = SUB / "src" / "pico2"
DEST = ROOT / "src" / "tnc"
REPO_URL = "https://github.com/klaNath/micro-aprs"
MARK = "# GENERATED by tools/vendor.py"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(SUB), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def render(dirty: bool) -> dict[str, str]:
    if not SRC_DIR.is_dir():
        sys.exit(f"[vendor] {SRC_DIR} がありません(サブモジュールの sparse-checkout を確認)")
    status = git("status", "--porcelain", "--", "src/pico2")
    if status and not dirty:
        sys.exit(
            "[vendor] src/pico2 に未コミットの変更があります。フォーク側でコミットするか --dirty を付けてください\n"
            + status
        )
    sha = git("rev-parse", "HEAD")
    rev = sha[:7] + ("+dirty" if status else "")
    out = {}
    for f in sorted(SRC_DIR.glob("*.py")):
        head = (
            f"{MARK} - DO NOT EDIT.\n"
            f"# Edit third_party/micro-aprs/src/pico2/{f.name} (branch pico2-subset) and re-run it.\n"
            f"# Source: {REPO_URL}/blob/{sha}/src/pico2/{f.name}  # noqa: E501\n"
            f"# Revision: {rev}\n"
        )
        out[f.name] = head + f.read_text(encoding="utf-8")
    return out


def main() -> int:
    for s in (sys.stdout, sys.stderr):  # 直接実行したときも UTF-8 で出す(Windows の既定は cp932)
        s.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dirty", action="store_true")
    a = ap.parse_args()

    want = render(a.dirty or a.check)
    have = {p.name: p for p in DEST.glob("*.py")} if DEST.is_dir() else {}
    if a.check:
        bad = []
        for name, text in want.items():
            p = have.get(name)
            # 出典行(コミット)以外が一致すれば OK(フォーク側でコミットしただけでは古くならない)
            if p is None or _body(p.read_text(encoding="utf-8")) != _body(text):
                bad.append(name)
        bad += [n for n, p in have.items() if n not in want and _generated(p)]
        if bad:
            print(f"[vendor] src/tnc/ が古い: {bad} → python tools/vendor.py を実行してください")
            return 1
        return 0

    DEST.mkdir(parents=True, exist_ok=True)
    for name, text in want.items():
        (DEST / name).write_text(text, encoding="utf-8", newline="\n")
    for name, p in have.items():
        if name not in want and _generated(p):
            p.unlink()
            print(f"[vendor] 削除: src/tnc/{name}")
    print(f"[vendor] {len(want)} ファイルを src/tnc/ に生成しました")
    return 0


def _generated(p: Path) -> bool:
    return p.read_text(encoding="utf-8").startswith(MARK)


def _body(text: str) -> str:
    return "\n".join(
        line for line in text.splitlines() if not line.startswith(("# Source: ", "# Revision: "))
    )


if __name__ == "__main__":
    sys.exit(main())
